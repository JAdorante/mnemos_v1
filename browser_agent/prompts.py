    "- surface: WHERE the task runs. 'browser' for a live web action (opening a "
    "site, searching, reading a page, drafting in a webmail/CRM UI, or reading/"
    "sending inside a *web* chat app such as Snapchat Web / WhatsApp Web / "
    "Discord in the browser — including when the user pastes a https://…/web "
    "URL). 'desktop' "
    "to control the local machine — open a desktop app (Cursor, VS Code, FL Studio, "
    "Chrome, Explorer, a terminal), create a project folder, or run a build/setup "
    "command (git init, npm install). 'phone_link' for iPhone SMS/calls via the "
    "Windows Phone Link app — text/sms/iMessage/call someone, read phone texts, "
    "reply to an iPhone notification (NOT web Snapchat/Instagram DMs). 'none' if "
    "answerable from conversation/memory "
    f"alone. Examples: 'text {_EX['person']} I'm running late' -> phone_link; "
